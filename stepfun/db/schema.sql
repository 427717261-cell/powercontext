-- 1) 集合元数据表：seekdb-js 在数据库内自动维护，记录逻辑名 → 物理表映射与索引配置
CREATE TABLE IF NOT EXISTS `sdk_collections` (
  `collection_id` char(32) NOT NULL DEFAULT (replace(uuid(),'-','')),
  `collection_name` string DEFAULT NULL,
  `settings` json DEFAULT NULL COMMENT 'Generated by SDK, do not modify',
  `created_at` timestamp NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` timestamp NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`collection_id`),
  UNIQUE KEY `idx_name` (`collection_name`) BLOCK_SIZE 16384 LOCAL
) ORGANIZATION INDEX DEFAULT CHARSET = utf8mb4 ROW_FORMAT = DYNAMIC COMPRESSION = 'zstd_1.3.8';

-- settings 示例（集合 docs）：
-- {"schema":{"vectorIndex":{"hnsw":{"distance":"l2","dimension":512}},
--            "fulltextIndex":{"analyzer":"ik","properties":{}}},"version":"v2"}

-- 2) 集合物理表：逻辑集合名 docs 对应 c$v2$<collection_id>
--    向量列 VECTOR(512) + HNSW 向量索引 + ik 中文全文索引
CREATE TABLE IF NOT EXISTS `c$v2$<collection_id>` (
  `_id` varbinary(512) NOT NULL,
  `document` string DEFAULT NULL,
  `embedding` VECTOR(512) DEFAULT NULL,
  `metadata` json DEFAULT NULL,
  PRIMARY KEY (`_id`),
  FULLTEXT KEY `idx_fts` (`document`) WITH PARSER ik PARSER_PROPERTIES=(ik_mode="smart") BLOCK_SIZE 16384,
  VECTOR KEY `idx_vec` (`embedding`)
    WITH (DISTANCE=L2, TYPE=HNSW, LIB=VSAG, M=16, EF_CONSTRUCTION=200, EF_SEARCH=64, SYNC_MODE=ASYNC)
    BLOCK_SIZE 16384
) ORGANIZATION HEAP DEFAULT CHARSET = utf8mb4 ROW_FORMAT = DYNAMIC COMPRESSION = 'zstd_1.3.8';

